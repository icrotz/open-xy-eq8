#!/usr/bin/env python3
"""Generate eq8 biquad coefficient table (coeffs.h).

Peaking (RBJ cookbook) biquads at fixed centers and Q. Coefficients depend
only on gain, so we tabulate them across STEPS+1 gain points from -RANGE_DB to
+RANGE_DB and embed them as a const header. The device interpolates by the
band's gain control, so there is no runtime trig, division or float.

Stored values are SCALED-DOWN, normalized coefficients in Q31
(round(coeff/SCALE * 2^31)), so each fits [-1, 1] and the device uses the SDK's
Q31 multiply, then multiplies the accumulator back by SCALE. With +/-24 dB a
peaking band's normalized b0 reaches ~2.1, so SCALE must be >= 4. Order per step:
  b0/SCALE, b1/SCALE, b2/SCALE, a1/SCALE, a2/SCALE   (a0 normalized to 1)
"""
import numpy as np

FS = 44100.0
CENTERS = [63.0, 125.0, 250.0, 500.0, 1000.0, 2000.0, 4000.0, 8000.0]
Q = 1.41
RANGE_DB = 24.0
SCALE = 4.0         # coeffs stored as coeff/SCALE; device multiplies output by SCALE
STEPS = 64          # intervals -> STEPS+1 = 65 table entries, index = control >> 25
Q31 = (1 << 31)


def peaking_half_q31(f0, q, gain_db):
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * np.pi * f0 / FS
    cosw = np.cos(w0)
    sinw = np.sin(w0)
    alpha = sinw / (2.0 * q)
    b0 = 1.0 + alpha * A
    b1 = -2.0 * cosw
    b2 = 1.0 - alpha * A
    a0 = 1.0 + alpha / A
    a1 = -2.0 * cosw
    a2 = 1.0 - alpha / A
    coeffs = np.array([b0, b1, b2, a1, a2]) / a0
    scaled = coeffs / SCALE
    q31 = np.round(scaled * Q31)
    # clamp to signed 32-bit
    q31 = np.clip(q31, -2147483648, 2147483647).astype(np.int64)
    # sanity: nothing should have hit the rail hard
    if np.any(np.abs(scaled) > 1.0 + 1e-6):
        raise SystemExit(f"coeff out of [-1,1] at f0={f0} g={gain_db}: {scaled} (raise SCALE)")
    return q31


def main():
    lines = []
    lines.append("#pragma once")
    lines.append("// Generated by tools/gen_coeffs.py -- do not edit by hand.")
    lines.append(f"// Scaled (/{SCALE:g}), normalized peaking-biquad coefficients in Q31:")
    lines.append(f"//   [band][step][b0, b1, b2, a1, a2]/{SCALE:g}, a0 == 1; device multiplies output by {SCALE:g}.")
    lines.append(f"// {len(CENTERS)} bands, {STEPS + 1} gain steps over +/-{RANGE_DB:g} dB, Q={Q:g}.")
    lines.append("#include <opxy/types.hpp>")
    lines.append("namespace eq8 {")
    lines.append(f"const unsigned kBands = {len(CENTERS)};")
    lines.append(f"const unsigned kSteps = {STEPS + 1};")
    lines.append(f"const opxy::i32 kCoeffs[{len(CENTERS)}][{STEPS + 1}][5] = {{")
    for f0 in CENTERS:
        lines.append(f"  {{ // {f0:g} Hz")
        for s in range(STEPS + 1):
            gain_db = -RANGE_DB + (2.0 * RANGE_DB) * s / STEPS
            c = peaking_half_q31(f0, Q, gain_db)
            vals = ", ".join(str(int(v)) for v in c)
            lines.append(f"    {{{vals}}},")
        lines.append("  },")
    lines.append("};")
    lines.append("}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
